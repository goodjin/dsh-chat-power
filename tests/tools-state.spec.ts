import { describe, expect, it } from 'vitest'
import { CHAT_TAB_ID, ToolsState } from '../src/tools-state.ts'
describe('conversation tabs workspace', () => {
  it('seeds a brand-new session with the conversation tab active', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const s = state.get('one')
    expect(s.tabs.map(t => t.kind)).toEqual(['chat'])
    expect(s.active).toBe(s.tabs[0]!.id)
  })
  it('seeds an existing session with the conversation tab active', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const s = state.get('one')
    expect(s.tabs.map(t => t.kind)).toEqual(['chat'])
    expect(s.active).toBe(CHAT_TAB_ID)
  })
  it('seeding twice keeps the first decision', () => {
    const state = new ToolsState()
    state.seed('one', false)
    state.seed('one', true)
    expect(state.get('one').tabs.map(t => t.kind)).toEqual(['chat'])
  })
  it('first send adds one conversation tab and switches to it, keeping tool tabs', () => {
    const state = new ToolsState()
    state.seed('one', false)
    state.open('one', 'files', 'Files', 'sidebar://files', undefined, true)
    state.activateChat('one')
    const s = state.get('one')
    expect(s.tabs.map(t => t.kind)).toEqual(['chat', 'files'])
    expect(s.active).toBe(CHAT_TAB_ID)
    state.activateChat('one')
    expect(state.get('one').tabs).toHaveLength(2)
    state.select('one', state.get('one').tabs.find(t => t.kind === 'files')!.id)
    expect(state.get('one').active).not.toBe(CHAT_TAB_ID)
  })
  it('an old session keeps a single conversation tab across sends', () => {
    const state = new ToolsState()
    state.seed('one', true)
    state.activateChat('one')
    state.activateChat('one')
    expect(state.get('one').tabs.map(t => t.kind)).toEqual(['chat'])
    expect(state.get('one').active).toBe(CHAT_TAB_ID)
  })
  it('the conversation tab cannot be closed, even with tool tabs around it', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const chat = state.get('one').tabs.find(t => t.kind === 'chat')!
    const browser = state.open('one', 'browser', 'Browser')
    state.close('one', CHAT_TAB_ID)
    expect(state.get('one').tabs.map(t => t.kind)).toEqual(['chat', 'browser'])
    expect(state.get('one').active).toBe(browser.id)
    state.close('one', browser.id)
    expect(state.get('one').tabs.map(t => t.kind)).toEqual(['chat'])
    expect(state.get('one').active).toBe(CHAT_TAB_ID)
    expect(chat.controller.signal.aborted).toBe(false)
    state.dispose()
  })
  it('isolates sessions and preserves tabs across activations', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const tab = state.open('one', 'browser', 'Browser')
    expect(tab.controller.signal.aborted).toBe(false)
    expect(state.get('two').tabs).toEqual([])
    state.activateChat('one')
    expect(state.get('one').tabs.at(-1)?.kind).toBe('browser')
    expect(state.get('one').tabs.at(-1)).toBe(tab)
    expect(state.get('one').active).toBe(CHAT_TAB_ID)
  })
  it('closing a tool tab aborts its resources and selects the remaining tab', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const a = state.open('one', 'files', 'Files', 'sidebar://files', undefined, true)
    const b = state.open('one', 'terminal', 'Terminal')
    state.close('one', b.id)
    expect(b.controller.signal.aborted).toBe(true)
    expect(a.controller.signal.aborted).toBe(false)
    expect(state.get('one').active).toBe(a.id)
    state.dispose()
    expect(a.controller.signal.aborted).toBe(true)
  })
  it('deduplicates resources but permits independent terminal and browser tabs', () => {
    const state = new ToolsState()
    state.seed('one', false)
    expect(state.open('one', 'files', 'Files', 'sidebar://files')).toBe(state.open('one', 'files', 'Files', 'sidebar://files'))
    const first = state.open('one', 'terminal', 'Terminal', 'sidebar://terminal', undefined, true)
    const second = state.open('one', 'terminal', 'Terminal', 'sidebar://terminal', undefined, true)
    expect(first.id).not.toBe(second.id)
    state.dispose()
  })
  it('markDraft 只改目标标签的草稿标记，其它标签不受影响', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser')
    state.markDraft('one', browser.id, true)
    expect(state.get('one').tabs.find(t => t.id === browser.id)?.draft).toBe(true)
    // 目标换成会话标签：会话标签被标记，browser 的标记保持原样（互不串扰）。
    state.markDraft('one', CHAT_TAB_ID, true)
    expect(state.get('one').tabs.find(t => t.kind === 'chat')?.draft).toBe(true)
    expect(state.get('one').tabs.find(t => t.id === browser.id)?.draft).toBe(true)
    state.markDraft('one', browser.id, false)
    expect(state.get('one').tabs.find(t => t.id === browser.id)?.draft).toBe(false)
  })
  it('关闭带草稿的标签会记住它；同 contentId 重新打开时恢复草稿标记并清除记忆', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser', 'sidebar://browser')
    state.markDraft('one', browser.id, true)
    state.close('one', browser.id)
    expect(state.closedDraft('one')?.contentId).toBe('sidebar://browser')
    const reopened = state.open('one', 'browser', 'Browser', 'sidebar://browser')
    expect(reopened.id).not.toBe(browser.id)
    expect(reopened.draft).toBe(true)
    expect(state.closedDraft('one')).toBeUndefined()
  })
  it('关闭不带草稿的标签不留草稿记忆', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser', 'sidebar://browser')
    state.close('one', browser.id)
    expect(state.closedDraft('one')).toBeUndefined()
  })
  it('dispose 清掉草稿记忆', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser', 'sidebar://browser')
    state.markDraft('one', browser.id, true)
    state.close('one', browser.id)
    state.dispose()
    expect(state.closedDraft('one')).toBeUndefined()
  })
})

describe('标签打开顺序（关掉后回上一个打开的标签）', () => {
  it('从工作区文件里点开文件再关掉：回到工作区文件，不是会话', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const files = state.get('one').tabs[0]!
    const file = state.open('one', 'local', 'a.md', 'edit://a.md')
    expect(state.get('one').active).toBe(file.id)
    state.close('one', file.id)
    expect(state.get('one').active).toBe(files.id)
    state.dispose()
  })
  it('关掉最后一个工具标签：回到会话', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser')
    state.close('one', browser.id)
    expect(state.get('one').active).toBe(CHAT_TAB_ID)
    state.dispose()
  })
  it('顺序表去重：再切一次旧标签，它成为最新的那个', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const browser = state.open('one', 'browser', 'Browser')
    const file = state.open('one', 'local', 'a.md', 'edit://a.md')
    // 再切回浏览器：顺序表里浏览器那条被挪到最后，不是留两条记录。
    state.select('one', browser.id)
    state.close('one', file.id)
    expect(state.get('one').active).toBe(browser.id)
    state.dispose()
  })
  it('连续打开两个文件，关掉后一个回到前一个', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const first = state.open('one', 'local', 'a.md', 'edit://a.md')
    const second = state.open('one', 'local', 'b.md', 'edit://b.md')
    state.close('one', second.id)
    expect(state.get('one').active).toBe(first.id)
    state.dispose()
  })
  it('关掉的不是当前标签：当前标签不动', () => {
    const state = new ToolsState()
    state.seed('one', false)
    const files = state.get('one').tabs[0]!
    const first = state.open('one', 'local', 'a.md', 'edit://a.md')
    const second = state.open('one', 'local', 'b.md', 'edit://b.md')
    state.select('one', files.id)
    state.close('one', second.id)
    expect(state.get('one').active).toBe(files.id)
    state.close('one', first.id)
    expect(state.get('one').active).toBe(files.id)
    state.dispose()
  })
  it('会话标签也在顺序表里：切到会话再关掉文件，回到会话', () => {
    const state = new ToolsState()
    state.seed('one', true)
    const file = state.open('one', 'local', 'a.md', 'edit://a.md')
    state.activateChat('one')
    state.close('one', file.id)
    expect(state.get('one').active).toBe(CHAT_TAB_ID)
    state.dispose()
  })
})
